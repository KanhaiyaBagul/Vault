/**
 * Untrusted Server Blind Multi-Map Store
 * Implements the server-side Encrypted Database (EDB) multi-map
 * for Cash et al. (NDSS 2014) and DynRH (Eurocrypt 2017) SSE schemes.
 * Zero external dependencies.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import type { BlindIndexEntry } from "./blind_index.ts";
import { computeIndexAddress } from "../crypto/trapdoors.ts";

export interface EncryptedPostingRecord {
  addressHex: string;
  encryptedValueHex: string;
  opaqueDocRef: string;
  counterIndex: number;
}

export interface SearchTrapdoorToken {
  trapdoorHex: string;
  trapdoorBytes: Uint8Array;
  count: number;
  addressHexList?: string[];
}

export interface SearchQueryPayload {
  queryType: "EXACT_WORD" | "SUBSTRING_CONJUNCTIVE";
  tokens: SearchTrapdoorToken[];
}

/**
 * In-memory simulation of the untrusted server's blind inverted index store.
 * The server only holds opaque 256-bit hash addresses and masked ciphertexts.
 * It possesses zero knowledge of plaintext document IDs or keyword tokens.
 */
export class ServerBlindStore {
  // Primary multi-map storage: Map<addressHex (L_c), BlindIndexEntry>
  private readonly store: Map<string, BlindIndexEntry> = new Map();
  private readonly persistenceFilePath?: string;

  constructor(persistencePath?: string) {
    this.persistenceFilePath = persistencePath;
    if (this.persistenceFilePath) {
      this.loadFromDisk();
    }
  }

  private loadFromDisk(): void {
    if (!this.persistenceFilePath) return;
    try {
      if (fs.existsSync(this.persistenceFilePath)) {
        const raw = fs.readFileSync(this.persistenceFilePath, "utf8");
        const entries = JSON.parse(raw);
        if (Array.isArray(entries)) {
          for (const entry of entries) {
            if (entry.addressHex && entry.encryptedValueHex) {
              this.store.set(entry.addressHex, entry);
            }
          }
        }
      }
    } catch (err) {
      console.warn("[ServerBlindStore] Failed to load persisted blind index:", err);
    }
  }

  private persistToDisk(): void {
    if (!this.persistenceFilePath) return;
    try {
      const dir = path.dirname(this.persistenceFilePath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      const entries = Array.from(this.store.values());
      fs.writeFileSync(this.persistenceFilePath, JSON.stringify(entries, null, 2), "utf8");
    } catch (err) {
      console.warn("[ServerBlindStore] Failed to persist blind index to disk:", err);
    }
  }

  /**
   * Bulk inserts blind index records into the encrypted multi-map.
   * @param entries Array of blind index entries generated by client
   */
  public insertEntries(entries: BlindIndexEntry[]): void {
    for (const entry of entries) {
      if (!entry.addressHex || !entry.encryptedValueHex) {
        throw new Error("Invalid BlindIndexEntry: addressHex and encryptedValueHex are required");
      }
      this.store.set(entry.addressHex, entry);
    }
    if (this.persistenceFilePath) {
      this.persistToDisk();
    }
  }

  /**
   * Retrieves encrypted posting records for a list of precomputed addresses.
   * Zero-crypto server evaluation: server needs no cryptographic keys.
   * @param addresses Array of opaque address hashes L_0, ..., L_{c-1}
   */
  public searchByAddresses(addresses: string[]): EncryptedPostingRecord[] {
    const results: EncryptedPostingRecord[] = [];
    for (let i = 0; i < addresses.length; i++) {
      const addr = addresses[i];
      const entry = this.store.get(addr);
      if (entry) {
        results.push({
          addressHex: entry.addressHex,
          encryptedValueHex: entry.encryptedValueHex,
          opaqueDocRef: entry.opaqueDocRef,
          counterIndex: i,
        });
      }
    }
    return results;
  }

  /**
   * Searches for a single keyword trapdoor tag_w up to counter c.
   * If kAddr is provided, server computes L_i = PRF(K_addr, tag_w || i).
   * @param kAddr Dedicated HMAC-SHA256 address key
   * @param trapdoorBytes Keyword trapdoor bytes (32 bytes)
   * @param count Current insertion count c from client state
   */
  public async searchSingleTrapdoor(
    kAddr: CryptoKey,
    trapdoorBytes: Uint8Array,
    count: number
  ): Promise<EncryptedPostingRecord[]> {
    if (count <= 0) {
      return [];
    }

    const addresses: string[] = [];
    for (let i = 0; i < count; i++) {
      const addr = await computeIndexAddress(kAddr, trapdoorBytes, i);
      addresses.push(addr);
    }

    return this.searchByAddresses(addresses);
  }

  /**
   * Evaluates a conjunctive query across multiple trapdoor tokens (e.g. N-grams).
   * Computes the set intersection of opaqueDocRef across all token posting lists.
   * Returns matching encrypted records for the intersecting documents from the primary token.
   * @param kAddr Dedicated HMAC-SHA256 address key
   * @param tokens Array of SearchTrapdoorTokens (one per N-gram or conjunctive keyword)
   */
  public async searchConjunctiveTrapdoors(
    kAddr: CryptoKey,
    tokens: SearchTrapdoorToken[]
  ): Promise<EncryptedPostingRecord[]> {
    if (tokens.length === 0) {
      return [];
    }

    // Step 1: Fetch posting lists for each token
    const postingsPerToken: EncryptedPostingRecord[][] = [];

    for (const token of tokens) {
      let records: EncryptedPostingRecord[];
      if (token.addressHexList && token.addressHexList.length > 0) {
        records = this.searchByAddresses(token.addressHexList);
      } else {
        records = await this.searchSingleTrapdoor(kAddr, token.trapdoorBytes, token.count);
      }
      postingsPerToken.push(records);
    }

    // If any token has 0 matches, the conjunction is immediately empty
    for (const list of postingsPerToken) {
      if (list.length === 0) {
        return [];
      }
    }

    // Step 2: Compute intersection of opaqueDocRef across all posting lists
    // Start with the document refs from the first (primary) token
    const primaryRecords = postingsPerToken[0];
    let candidateDocRefs = new Set(primaryRecords.map(r => r.opaqueDocRef));

    for (let t = 1; t < postingsPerToken.length; t++) {
      const currentTokenDocRefs = new Set(postingsPerToken[t].map(r => r.opaqueDocRef));
      const nextCandidateSet = new Set<string>();
      for (const docRef of candidateDocRefs) {
        if (currentTokenDocRefs.has(docRef)) {
          nextCandidateSet.add(docRef);
        }
      }
      candidateDocRefs = nextCandidateSet;
      if (candidateDocRefs.size === 0) {
        return [];
      }
    }

    // Step 3: Return primary token records for surviving intersecting documents
    const intersectingRecords = primaryRecords.filter(r => candidateDocRefs.has(r.opaqueDocRef));
    return intersectingRecords;
  }

  /**
   * Pure zero-crypto conjunctive search using client-supplied address lists.
   * Server performs table lookups and set intersection without holding any keys.
   * @param tokenAddressLists Array of address lists, one per token / N-gram
   */
  public searchConjunctiveByAddresses(tokenAddressLists: string[][]): EncryptedPostingRecord[] {
    if (tokenAddressLists.length === 0) {
      return [];
    }

    const postingsPerToken: EncryptedPostingRecord[][] = [];
    for (const addresses of tokenAddressLists) {
      const records = this.searchByAddresses(addresses);
      if (records.length === 0) {
        return [];
      }
      postingsPerToken.push(records);
    }

    const primaryRecords = postingsPerToken[0];
    let candidateDocRefs = new Set(primaryRecords.map(r => r.opaqueDocRef));

    for (let t = 1; t < postingsPerToken.length; t++) {
      const currentTokenDocRefs = new Set(postingsPerToken[t].map(r => r.opaqueDocRef));
      const nextCandidateSet = new Set<string>();
      for (const docRef of candidateDocRefs) {
        if (currentTokenDocRefs.has(docRef)) {
          nextCandidateSet.add(docRef);
        }
      }
      candidateDocRefs = nextCandidateSet;
      if (candidateDocRefs.size === 0) {
        return [];
      }
    }

    return primaryRecords.filter(r => candidateDocRefs.has(r.opaqueDocRef));
  }

  /**
   * Returns the total count of stored entries in the blind index.
   */
  public size(): number {
    return this.store.size;
  }

  /**
   * Clears all stored entries (for test cleanup).
   */
  public clear(): void {
    this.store.clear();
  }
}
